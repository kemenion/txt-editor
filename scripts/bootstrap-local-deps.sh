#!/usr/bin/env bash
# Bootstrap a user-space build sysroot. No sudo, no writes outside third_party/.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TP="$ROOT/third_party"
TOOLS="$TP/tools"
SYSROOT="$TP/sysroot"
DEBS="$TP/debs"
mkdir -p "$TOOLS" "$SYSROOT" "$DEBS"

log() { printf '[bootstrap] %s\n' "$*"; }
fail() { printf '[bootstrap] ERROR: %s\n' "$*" >&2; exit 1; }

for cmd in curl tar unzip dpkg-deb apt-get; do
    command -v "$cmd" >/dev/null 2>&1 || fail "missing host command: $cmd"
done

# --- CMake/Ninja and GTK3 development closure --------------------------------
PKGS=(
    cmake cmake-data ninja-build libjsoncpp26 librhash1
    pkgconf pkgconf-bin libpkgconf3
    libgtk-3-dev libgtk-3-common libgtk-3-0t64
    libatk1.0-0t64 libatk-bridge2.0-0t64 libatspi2.0-0t64
    libcairo2 libcairo-gobject2 libpango-1.0-0 libpangocairo-1.0-0 libpangoft2-1.0-0
    libgdk-pixbuf-2.0-0 libglib2.0-0t64
    libharfbuzz0b libgraphite2-3 libthai0 libdatrie1 libxft2
    libjpeg62-turbo libtiff6 libwebp7 libsharpyuv0 libzstd1 liblzma5 liblerc4 libdeflate0
    libepoxy0 libfontconfig1 libfreetype6 libfribidi0 libbrotli1
    libwayland-client0 libwayland-cursor0 libwayland-egl1
    libx11-6 libx11-xcb1 libxcomposite1 libxcursor1 libxdamage1 libxext6
    libxfixes3 libxi6 libxinerama1 libxrandr2 libxrender1 libxtst6 libxkbcommon0
    libxcb1 libxcb-render0 libxcb-shm0 libxcb-glx0 libxcb-util1 libxcb-image0
    libxcb-keysyms1 libxcb-randr0 libxcb-xfixes0 libxcb-shape0 libxcb-xkb1
    libxkbcommon-x11-0 libxcb-icccm4 libxcb-sync1 libxcb-xinerama0 libxcb-xrm0
    libxau6 libxdmcp6 libbsd0 libmd0 liblz4-1
    libegl1 libgl1 libglx0 libopengl0 libglvnd0 libcloudproviders0
    libexpat1 libpng16-16t64 zlib1g libbz2-1.0 libffi8
    libmount1 libblkid1 libuuid1 libpcre2-8-0 libpcre2-32-0 libselinux1 libsepol2
    libsystemd0 libdbus-1-3 libpixman-1-0
    libglib2.0-dev libglib2.0-dev-bin libglib2.0-bin
    libgio-2.0-dev libgio-2.0-dev-bin girepository-tools
    libcairo2-dev libpixman-1-dev
    libpango1.0-dev libharfbuzz-dev libgraphite2-dev libicu-dev
    libthai-dev libdatrie-dev libxft-dev libjpeg-dev libjpeg62-turbo-dev libtiff-dev libwebp-dev
    libsharpyuv-dev libzstd-dev liblzma-dev liblerc-dev libdeflate-dev
    libgdk-pixbuf-2.0-dev
    libatk1.0-dev libatk-bridge2.0-dev libatspi2.0-dev libdbus-1-dev
    libepoxy-dev
    libfontconfig-dev libfreetype-dev libfribidi-dev libbrotli-dev
    libwayland-dev wayland-protocols
    libx11-dev libx11-xcb-dev
    libxcomposite-dev libxcursor-dev libxdamage-dev libxext-dev
    libxfixes-dev libxi-dev libxtst-dev libxinerama-dev libxrandr-dev libxrender-dev
    libxkbcommon-dev
    libxcb1-dev libxcb-render0-dev libxcb-shm0-dev libxcb-glx0-dev
    libxau-dev libxdmcp-dev libbsd-dev libpthread-stubs0-dev
    x11proto-dev xtrans-dev
    libegl1-mesa-dev libegl-dev libgl-dev libglx-dev libopengl-dev libglvnd-dev
    libcloudproviders-dev
    libexpat1-dev zlib1g-dev libpng-dev libbz2-dev
    libffi-dev libmount-dev libblkid-dev uuid-dev libpcre2-dev
    libselinux1-dev libsepol-dev libsysprof-capture-4-dev libsystemd-dev
    squashfs-tools
)

download_deb() {
    local pkg="$1"
    if compgen -G "$DEBS/${pkg}_*.deb" >/dev/null; then
        return 0
    fi
    log "apt-get download $pkg"
    (cd "$DEBS" && apt-get download "$pkg")
}

for pkg in "${PKGS[@]}"; do
    download_deb "$pkg"
done

log "extracting Debian packages into $SYSROOT"
for deb in "$DEBS"/*.deb; do
    dpkg-deb -x "$deb" "$SYSROOT"
done

# --- environment -------------------------------------------------------------
cat > "$TP/env.sh" <<EOF
# Generated by scripts/bootstrap-local-deps.sh. Source this file.
export TXT_ROOT="$ROOT"
export SYSROOT="$SYSROOT"
export WX_PREFIX="$TP/wx-install"
export CMAKE="$SYSROOT/usr/bin/cmake"
export NINJA="$SYSROOT/usr/bin/ninja"
export PKG_CONFIG_EXECUTABLE="$SYSROOT/usr/bin/pkg-config"
export PKG_CONFIG_SYSROOT_DIR="$SYSROOT"
export PKG_CONFIG_PATH="$SYSROOT/usr/lib/x86_64-linux-gnu/pkgconfig:$SYSROOT/usr/share/pkgconfig"
export LD_LIBRARY_PATH="$SYSROOT/usr/lib/x86_64-linux-gnu\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
export CPATH="$SYSROOT/usr/include:$SYSROOT/usr/include/x86_64-linux-gnu\${CPATH:+:\$CPATH}"
export LIBRARY_PATH="$SYSROOT/usr/lib/x86_64-linux-gnu:/usr/lib/x86_64-linux-gnu\${LIBRARY_PATH:+:\$LIBRARY_PATH}"
export PATH="$SYSROOT/usr/bin:$TOOLS:$TOOLS/cmake/bin\${PATH:+:\$PATH}"
EOF
chmod +x "$TP/env.sh"
# shellcheck disable=SC1091
source "$TP/env.sh"

[[ -x "$CMAKE" ]] || fail "CMake bootstrap failed"
[[ -x "$NINJA" ]] || fail "Ninja bootstrap failed"
[[ -x "$SYSROOT/usr/bin/pkg-config" ]] || fail "pkgconf bootstrap failed"
log "pkgconf: $("$SYSROOT/usr/bin/pkg-config" --version)"
log "gtk+-3.0: $("$SYSROOT/usr/bin/pkg-config" --modversion gtk+-3.0 2>/dev/null || echo 'NOT FOUND')"
log "done. Run: source third_party/env.sh"
